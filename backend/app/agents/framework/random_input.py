class RandomInputAgent(FrameworkAgent):
    method_name = "random_input"
    method_label = "隨機刺激（Random Input）"
    short_label = "隨機刺激"
    description = (
        "抽一個完全無關的隨機詞彙，強迫把它跟你們的主題湊在一起，逼出意外的連結。"
    )
    tutorial_intro = (
        "抽一個跟主題完全無關的隨機詞彙，強迫自己把它跟主題湊在一起，用不合理的連結逼出跳脫慣性的點子，適合已經有大方向、只是想不出新意的情況。"
    )
    tutorial_how_to = (
        "先講你們的主題方向，接著系統會給一個隨機詞彙，想辦法硬把它跟主題湊在一起想出一個點子，重複三次後，挑一個比較有潛力的延伸。"
    )
    steps = [
        StepSpec(
            "topic",
            "你們目前的方向或想解決的領域大致是什麼？就算還很模糊也沒關係。",
        ),
        StepSpec("random_word_1", ""),
        StepSpec("random_word_2", ""),
        StepSpec("random_word_3", ""),
        StepSpec(
            "pick_best",
            "剛剛三次的隨機聯想裡，哪一個組合你覺得比較有潛力？再稍微延伸一下這個方向。",
        ),
    ]

    def question_for(self, index: int) -> str:
        if index == 1:
            word = random.choice(_WORD_POOL_A)
            return (
                f"不用管合不合理，想一下「{word}」帶給你的感覺、特性或畫面，"
                "硬套進你們的主題，逼出一個點子。"
            )
        if index == 2:
            word = random.choice(_WORD_POOL_B)
            return (
                f"再來一次，這次用「{word}」——一樣不用管合不合理，"
                "抓住它的感覺或特性，跟你們的主題湊在一起，想出另一個點子。"
            )
        if index == 3:
            word = random.choice(_WORD_POOL_C)
            return (
                f"最後一次，這次用「{word}」——一樣不用管合不合理，"
                "抓住它的感覺或特性，跟你們的主題湊在一起，想出另一個點子。"
            )
        return super().question_for(index)
